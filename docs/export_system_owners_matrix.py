def write_sheet(ws, title_row, rows):
    ws.append(HEADERS)
    for cell in ws[1]:
        cell.font = Font(bold=True)
        cell.alignment = Alignment(wrap_text=True, vertical="top")
    for row in rows:
        ws.append(list(row))
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
    for i, _ in enumerate(HEADERS, 1):
        ws.column_dimensions[get_column_letter(i)].width = 22 if i == 1 else 28
    ws.column_dimensions["E"].width = 36


def main():
    wb = Workbook()
    ws1 = wb.active
    ws1.title = "Учёт и MD (12)"
    write_sheet(ws1, None, SHEET1)

    ws2 = wb.create_sheet("Корпоративные (15)")
    write_sheet(ws2, None, SHEET2)

    ws3 = wb.create_sheet("Уточнить (9)")
    write_sheet(ws3, None, SHEET3)

    ws4 = wb.create_sheet("Пояснения")
    for line in LEGEND:
        ws4.append([line])
    ws4.column_dimensions["A"].width = 90

    wb.save(OUT)
    print(OUT)


if __name__ == "__main__":
    main()
